<!-- wp:paragraph -->
<p>For fifteen years the question was simple: where do we rank. It was a good question while search results were a list of links and the job was to be near the top of that list. That is no longer what most people see.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>When a buyer asks a model which vendors are worth considering, they do not get ten links. They get a paragraph naming two or three companies. <strong>You are either in that paragraph or you are not.</strong> There is no position four.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">What share of answer actually is</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Take the questions your buyers genuinely ask before they contact anyone. Not keywords, questions. Run each one across the models they use. Count how many of those responses name you.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>That percentage is your share of answer. If you are named in fourteen out of twenty-four responses, your share of answer is 58 percent for that question set.</p>
<!-- /wp:paragraph -->

<!-- wp:pattern {"slug":"thallo-blog/stat-row"} /-->

<!-- wp:heading -->
<h2 class="wp-block-heading">Why rankings stopped telling you what you need</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A ranking describes your position on a results page. That metric assumed the page was the destination. Increasingly it is the end of the journey, not the middle.</p>
<!-- /wp:paragraph -->

<!-- wp:pattern {"slug":"thallo-blog/pull-quote"} /-->

<!-- wp:paragraph -->
<p>Share of answer replaces the assumption. It does not ask where you sit relative to competitors on a page. It asks whether the model considered you a credible enough source to put your name in front of someone making a decision.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">How to measure it</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The method matters more than the tool. Three things make the number meaningful rather than decorative:</p>
<!-- /wp:paragraph -->

<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list">
<!-- wp:list-item -->
<li><strong>A fixed question set.</strong> Twenty to thirty questions your buyers actually ask, written once and not changed. If the questions move, the number means nothing across time.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li><strong>The same models, on a schedule.</strong> Responses vary run to run. Monthly, across the same models, smooths that out into something you can trend.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li><strong>Competitors in the same run.</strong> Your number alone is not information. Your number against the three names you lose to is.</li>
<!-- /wp:list-item -->
</ol>
<!-- /wp:list -->

<!-- wp:heading -->
<h2 class="wp-block-heading">What actually moves the number</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>This is where most teams get it wrong, because the instinct is to publish more and the answer is to publish differently.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Being the source rather than a source</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Models name what other credible places already reference. Original research gets cited because it contains something that exists nowhere else. A summary of what everyone else said gives a model no reason to name you specifically.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Structure it can parse</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>A direct answer near the top, headings shaped like the questions people ask, and markup that removes ambiguity about who wrote this and what it claims.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Presence where the models look</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Your site is one input. Communities, publications and the places your category argues in public are others, and they carry more weight than most teams expect.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Where to start</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Write the twenty questions. Run them once. The gap between what you assumed and what comes back is usually the most useful thing you will learn this quarter.</p>
<!-- /wp:paragraph -->

